function getGroupedData(p: ExcelExportParams, fv: Voucher[]): { groupName: string, lines: any[] }[] {
  const map = new Map<string, any[]>()
  
  fv.forEach(v => {
    v.lines.forEach(l => {
      // If an account filter is applied, only group the lines that match the filter.
      if (p.reportType === 'LedgerBreakup' && p.filters?.accountId && p.filters.accountId !== 'All') {
        if (l.accountId !== p.filters.accountId) return
      }

      let key = 'Uncategorized'
      
      if (p.reportType === 'LedgerBreakup') {
        key = p.accounts.find(a => a.id === l.accountId)?.name || 'Unknown Account'
      } else if (p.reportType === 'PropertyBreakup') {
        const lease = p.leases?.find(lx => lx.leaseNumber === v.reference || (l.referenceType === 'Lease' && l.referenceId === lx.id))
        const prop = p.properties?.find(px => px.id === (lease?.propertyId || (l.referenceType === 'Property' ? l.referenceId : null)))
        key = prop?.name || 'Unassigned Property'
      } else if (p.reportType === 'SupplierBreakup') {
        key = v.reference || v.description || 'Unknown Supplier'
      } else if (p.reportType === 'TenantBreakup') {
        const lease = p.leases?.find(lx => lx.leaseNumber === v.reference || (l.referenceType === 'Lease' && l.referenceId === lx.id))
        const tenant = p.tenants?.find(tx => tx.id === lease?.tenantId)
        key = tenant?.name || v.reference || 'Unknown Tenant'
      }
      
      if (!map.has(key)) map.set(key, [])
      map.get(key)!.push({
        v, l,
        accName: p.accounts.find(a => a.id === l.accountId)?.name || l.accountId,
        desc: l.narration || v.description || ''
      })
    })
  })
  
  const grouped: { groupName: string, lines: any[] }[] = []
  Array.from(map.entries()).forEach(([key, items]) => {
    grouped.push({
      groupName: key,
      lines: items
    })
  })
  
  // Sort alphabetically by groupName
  return grouped.sort((a, b) => a.groupName.localeCompare(b.groupName))
}

function sheetBreakup(p: ExcelExportParams, fv: Voucher[], coverData?: any): any {
  const rows: XCell[][] = []
  
  if (coverData) {
    rows.push(...coverData.rows, [], [])
  }
  
  const groupedData = getGroupedData(p, fv)
  
  groupedData.forEach(group => {
    let totDr = 0, totCr = 0
    group.lines.forEach((x: any) => {
      if (x.l.type === 'Debit') totDr += x.l.amount
      else totCr += x.l.amount
    })
    
    rows.push(sectionRow(`  ${group.groupName.toUpperCase()} - (Debits: ${p.currency} ${totDr.toFixed(2)} | Credits: ${p.currency} ${totCr.toFixed(2)})`, 8, C.primaryDark))
    const hdrs = ['Date', 'Voucher', 'Reference', 'Type', 'Account', 'Description', 'Debit', 'Credit']
    rows.push(hdrs.map(h => hCell(h, { bg: C.primary })))
    
    group.lines.forEach((x: any) => {
      const lb = C.grayLight
      rows.push([
        dCell(x.v.date, { bg: lb, center: true }),
        dCell(x.v.voucherNumber, { bg: lb, center: true }),
        dCell(x.v.reference || '-', { bg: lb, center: true }),
        dCell(x.v.type, { bg: lb, center: true }),
        dCell(x.accName, { bg: lb }),
        dCell(x.desc, { bg: lb }),
        x.l.type === 'Debit' ? cCell(x.l.amount, lb) : eCell(lb),
        x.l.type === 'Credit' ? cCell(x.l.amount, lb) : eCell(lb)
      ])
    })
    rows.push([]) // Spacer
  })
  
  const offset = coverData ? coverData.rows.length + 2 : 0

  return buildWS(rows, {
    freeze: { r: 1 + offset, c: 0 }, filterRow: offset,
    colW: [{ wch: 14 }, { wch: 16 }, { wch: 16 }, { wch: 14 }, { wch: 25 }, { wch: 40 }, { wch: 14 }, { wch: 14 }],
    merges: coverData?.merges,
    rowHeights: coverData?.rowHeights
  })
}

