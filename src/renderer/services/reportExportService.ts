function generatePdfCoverPage(doc: any, title: string, subtitle: string, periodLabel: string, currency: string, totalTxns?: number, moduleName?: string, generatedBy?: string): number {
  const actualGeneratedBy = generatedBy || (typeof localStorage !== 'undefined' ? localStorage.getItem('loggedInUser') : null) || 'User'
  const pageWidth = doc.internal.pageSize.getWidth()
  const centerX = pageWidth / 2

  doc.setTextColor(0, 0, 0)
  doc.setFontSize(12)
  doc.setFont('helvetica', 'bold')
  doc.text('Sameer Ishaq Harmoudi', centerX, 15, { align: 'center' })

  doc.setDrawColor(200, 200, 200)
  doc.setLineWidth(0.5)
  doc.line(0, 23, pageWidth, 23)

  doc.setTextColor(0, 0, 0)
  doc.setFontSize(12)
  doc.setFont('helvetica', 'bold')
  doc.text(title.toUpperCase(), centerX, 30, { align: 'center' })

  let myY = 38

  if (subtitle) {
    doc.setTextColor(100, 116, 139)
    doc.setFontSize(10)
    doc.setFont('helvetica', 'normal')
    doc.text(subtitle, centerX, 36, { align: 'center' })
    myY = 46
  }

  doc.setTextColor(100, 116, 139)
  doc.setFontSize(8)
  doc.setFont('helvetica', 'bold')
  
  const dateOptions: Intl.DateTimeFormatOptions = { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: false }
  const generatedOn = new Date().toLocaleString('en-GB', dateOptions).replace(',', '')

  const metaItems = [
    { label: 'Reporting Period', val: periodLabel },
    { label: 'Currency', val: currency },
    { label: 'Generated By', val: actualGeneratedBy },
    { label: 'Generated On', val: generatedOn },
  ]
  if (totalTxns !== undefined) {
    metaItems.push({ label: 'Total Records', val: totalTxns.toString() })
  }

  let finalModuleName = moduleName
  if (!finalModuleName && typeof document !== 'undefined') {
    const appShell = document.querySelector('.app-shell')
    if (appShell) {
      const activeModule = appShell.getAttribute('data-module')
      if (activeModule === 'property') finalModuleName = 'Properties Management'
      else if (activeModule === 'investment') finalModuleName = 'Investment'
    }
  }
  if (finalModuleName) {
    metaItems.push({ label: 'Portfolio', val: finalModuleName })
  }

  const validMetaItems = metaItems.filter(item => item.val && String(item.val).trim() !== '')

  const columns = 3
  const rowHeight = 7
  const leftMargin = 14
  const colWidth = (pageWidth - (leftMargin * 2)) / columns
  
  validMetaItems.forEach((item, index) => {
    const col = index % columns
    const row = Math.floor(index / columns)
    
    // Left-aligned dynamic grid based on page width
    const startX = leftMargin + (col * colWidth)
    const itemY = myY + (row * rowHeight)

    doc.setFont('helvetica', 'bold')
    doc.text(item.label + ':', startX, itemY)
    
    const labelWidth = doc.getTextWidth(item.label + ': ')
    doc.setFont('helvetica', 'normal')
    doc.text(item.val, startX + labelWidth, itemY)
  })

  // Update myY based on how many rows we used
  const totalRows = Math.ceil(validMetaItems.length / columns)
  myY += (totalRows * rowHeight) + 4

  doc.setFont('helvetica', 'normal')
  doc.setTextColor(0, 0, 0)

  return myY + 7
}

